/**
 * Writes src/sources/gesla/tidal-rivers.ts: GESLA 4.1's river and lake records
 * that carry a tide (`tidal` in the adapter), which QC treats as tide gauges. The
 * release is static, so this runs once per release. It reads each record from
 * the release's zip, as backfill does, a few at a time.
 *
 *   node scripts/gesla-tidal-rivers.ts
 */
import { writeFile } from "node:fs/promises";
import { HttpError } from "../src/http.ts";
import { pool } from "../src/lake/recent.ts";
import { DROPPED } from "../src/sources/gesla/dropped.ts";
import { parse, readRecord, stations } from "../src/sources/gesla/index.ts";
import { tidal } from "../src/sources/gesla/tidal.ts";

// QC treats only rivers and lakes as still water; DROPPED's hold another gauge's values.
const records = (await stations())
  .filter((s) => (s.kind === "river" || s.kind === "lake") && !DROPPED.has(s.source_id))
  .map((s) => s.source_id);
const found: string[] = [];
let done = 0;
/** A record's text, tried again after a pause, since iCloud refuses a request now and then (a 401); other errors fail at once. */
async function read(file: string, attempt = 1): Promise<string> {
  try {
    return await readRecord(file);
  } catch (error) {
    if (!(error instanceof HttpError)) throw new Error(`${file}: ${String(error)}`);
    if (attempt >= 5) throw new Error(`${file}: ${String(error)}`);
    await new Promise((resolve) => setTimeout(resolve, 30_000 * attempt));
    return read(file, attempt + 1);
  }
}

await pool(records, 4, async (file) => {
  const record = parse(await read(file), file, null);
  try {
    if (tidal(record)) found.push(file);
  } catch (error) {
    throw new Error(`${file}: ${String(error)}`);
  }
  if (++done % 50 === 0) console.log(`${done} of ${records.length} read, ${found.length} tidal`);
});
found.sort();

await writeFile(
  new URL("../src/sources/gesla/tidal-rivers.ts", import.meta.url),
  `/**
 * GESLA's river and lake records whose lunar tide, M2 and O1 together, is
 * \`TIDE_M\` or more over their last year (\`tidal\`), so QC treats them as
 * tide gauges rather than pooled rivers (\`qcFor\` in src/lake/recent.ts).
 * Generated by \`node scripts/gesla-tidal-rivers.ts\`: ${found.length} of ${records.length}.
 */
export const TIDAL_RIVERS = new Set([
${found.map((f) => `  ${JSON.stringify(f)},`).join("\n")}
]);
`,
);
console.log(`${found.length} of ${records.length} river and lake records are tidal`);
