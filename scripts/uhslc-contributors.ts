/**
 * Reads every UHSLC research-quality documentation file
 * (`rqds/<ocean>/doc/qa<id>.dmt`, about 720 of a few KB each, a second apart)
 * and records each station's contributor and any terms of its own, from
 * `src/sources/uhslc/notices.ts`. Writes `src/sources/uhslc/contributors.ts`,
 * which the adapter reads, and the table by contributor in
 * docs/uhslc-contributors.md. Every file is fetched fresh, so a notice UHSLC
 * adds to a file is seen; the files are Latin-1.
 *
 *   node scripts/uhslc-contributors.ts
 */
import { writeFile } from "node:fs/promises";
import { getJson, getText } from "../src/http.ts";
import { contributorOf, NOTICES } from "../src/sources/uhslc/notices.ts";

const RQDS = "https://uhslc.soest.hawaii.edu/rqds";
const OCEANS = ["pacific", "atlantic", "indian"];

let last = 0;
const pace = async () => {
  const wait = last + 1000 - Date.now();
  if (wait > 0) await new Promise((resolve) => setTimeout(resolve, wait));
  last = Date.now();
};

const stations: Record<string, { contributor: string | null; notice: string | null }> = {};
/** Terms-like text no notice matched, for a person to read and add to NOTICES. */
const unmatched: string[] = [];
// ERDDAP lists some records UHSLC has no documentation file for; they're
// recorded with no contributor, so the adapter knows they've been looked for.
const listed = (
  await getJson<{ table: { rows: [number, string][] } }>(
    `https://uhslc.soest.hawaii.edu/erddap/tabledap/global_hourly_rqds.json?${encodeURIComponent("uhslc_id,version")}&${encodeURIComponent("distinct()")}`,
    { fresh: true },
  )
).table.rows;
if (!listed.length) throw new Error("ERDDAP listed no research-quality records");
for (const [id, version] of listed)
  stations[`${String(id).padStart(3, "0")}${version.toLowerCase()}`] = {
    contributor: null,
    notice: null,
  };
for (const ocean of OCEANS) {
  // The listing changes as UHSLC adds records, so it's never cached.
  const index = await getText(`${RQDS}/${ocean}/doc/`, { fresh: true, pace });
  const files = [...new Set(index.match(/qa\d{3}[a-z]\.dmt/g))];
  if (!files.length) throw new Error(`No documentation files listed for ${ocean}`);
  for (const file of files) {
    const bytes = await getText(`${RQDS}/${ocean}/doc/${file}`, { pace, base64: true });
    const text = Buffer.from(bytes, "base64").toString("latin1");
    const flat = text.replace(/\s+/g, " ");
    let notice = noticeOf(flat);
    if (!notice && /copyright|permission|commercial|licen[cs]e|terms of use/i.test(flat)) {
      unmatched.push(file.slice(2, 6));
      notice = "unreviewed";
    }
    stations[file.slice(2, 6)] = { contributor: contributorOf(text), notice };
  }
}

/** The most restrictive notice a file carries: one that bars commercial use first. */
function noticeOf(flat: string): string | null {
  const found = Object.entries(NOTICES).filter(([, n]) => n.pattern.test(flat));
  found.sort(([, a], [, b]) => Number(a.commercial_use) - Number(b.commercial_use));
  return found[0]?.[0] ?? null;
}

const sorted = Object.fromEntries(Object.entries(stations).sort(([a], [b]) => a.localeCompare(b)));
await writeFile(
  new URL("../src/sources/uhslc/contributors.ts", import.meta.url),
  `// Generated by scripts/uhslc-contributors.ts from UHSLC's documentation files; don't edit.
/** Each research-quality record's contributor and notice (a key of NOTICES), by \`<number><version>\`. */
export const CONTRIBUTORS: Record<string, { contributor: string | null; notice: string | null }> =
  ${JSON.stringify(sorted)};
`,
);

// One row per contributor and notice, most stations first.
const groups = new Map<string, { contributor: string; notice: string | null; ids: string[] }>();
for (const [id, s] of Object.entries(sorted)) {
  const contributor = s.contributor ?? "Not named";
  const key = `${contributor}\u0000${s.notice}`;
  const group = groups.get(key) ?? { contributor, notice: s.notice, ids: [] };
  group.ids.push(id);
  groups.set(key, group);
}
const rows = [...groups.values()].sort(
  (a, b) => b.ids.length - a.ids.length || a.contributor.localeCompare(b.contributor),
);
const terms = (notice: string | null) => {
  if (!notice) return "UHSLC's";
  const n = NOTICES[notice]!;
  return n.url ? `${n.terms} [Terms](${n.url})` : n.terms;
};
const commercial = (notice: string | null) =>
  notice === null || NOTICES[notice]!.commercial_use ? "yes" : "no";
await writeFile(
  new URL("../docs/uhslc-contributors.md", import.meta.url),
  `# UHSLC contributors

Generated by \`node scripts/uhslc-contributors.ts\` from UHSLC's research-quality documentation files (\`https://uhslc.soest.hawaii.edu/rqds/<ocean>/doc/qa<id>.dmt\`), ${Object.keys(sorted).length} records. Every station UHSLC serves openly is in the public lake under UHSLC's terms ("may be used and redistributed for free but is not intended for legal use"). Contributors whose own terms are stricter are being asked for permission to republish; their stations would come out of the lake if one refuses. Where a contributor's file carries terms of its own, the station's \`commercial_use\` follows them and its \`attribution\` adds the contributor's credit; [src/sources/uhslc/notices.ts](../src/sources/uhslc/notices.ts) holds those terms. The fast-delivery series take their latest research-quality version's file; those with no research-quality data have no file, and nor do a few research-quality records, so their contributor is unknown and UHSLC's terms apply. A record released since the last scan is tagged non-commercial until a rescan reads it.

| Contributor | Records | Commercial use | Terms | Records, e.g. |
| --- | --: | --- | --- | --- |
${rows
  .map(
    (r) =>
      `| ${r.contributor} | ${r.ids.length} | ${commercial(r.notice)} | ${terms(r.notice)} | ${r.ids.slice(0, 6).join(", ")}${r.ids.length > 6 ? ", …" : ""} |`,
  )
  .join("\n")}
`,
);
console.log(`${Object.keys(sorted).length} records, ${rows.length} contributor rows`);
if (unmatched.length)
  console.log(
    `Terms text no notice matched, to read and add to notices.ts: ${unmatched.join(", ")}`,
  );
