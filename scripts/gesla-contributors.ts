/**
 * Writes src/sources/gesla/contributors.md: GESLA 4.1's records by contributor, with
 * the terms `src/sources/gesla/contributors.ts` tags them with, from the
 * release's metadata CSV as the adapter lists it.
 *
 *   node scripts/gesla-contributors.ts
 */
import { writeFile } from "node:fs/promises";
import { stations, withheldFiles } from "../src/sources/gesla/index.ts";
import { CONTRIBUTORS } from "../src/sources/gesla/contributors.ts";
import { DROPPED } from "../src/sources/gesla/dropped.ts";

// The adapter leaves out withheld records; those in DROPPED hold another gauge's values.
const all = await stations();
const list = all.filter((s) => !DROPPED.has(s.source_id));
const groups = Map.groupBy(list, (s) => s.contributor);
const rows = [...groups]
  .sort(([a, x], [b, y]) => y.length - x.length || a.localeCompare(b))
  .map(([abbrev, records]) => {
    const c = CONTRIBUTORS[abbrev.toUpperCase()]!;
    const commercial = records.filter((s) => s.commercial_use).length;
    const use =
      commercial === records.length ? "yes" : commercial === 0 ? "no" : `${commercial} of them`;
    const linked = records.filter((s) => s.same_as.length).length;
    return `| ${abbrev} | ${c.name} | ${records.length} | ${use} | ${linked} | ${c.terms} |`;
  });

await writeFile(
  new URL("../src/sources/gesla/contributors.md", import.meta.url),
  `# GESLA contributors

Generated by \`node scripts/gesla-contributors.ts\` from GESLA 4.1's metadata, ${list.length} records. Records whose values are another gauge's are listed without values and left out of that count (see the adapter's README), and so are the ${withheldFiles.length} records the South African Navy Hydrographic Office's refusal covers, which aren't in the store at all: SANHO refused permission to republish any of its data ([#80](https://github.com/openwatersio/stillwell/issues/80), [#82](https://github.com/openwatersio/stillwell/issues/82)). Every other record GESLA serves is in the public store, credited to GESLA and its contributor: GESLA serves them all openly, so under the store's rule each goes in with its contributor's terms tagged, and only data a source itself withholds, or a copy of a UHSLC record whose contributor refused republication, stays out. Where a contributor's own terms ask for permission to republish, it's being asked for: JODC ([#47](https://github.com/openwatersio/stillwell/issues/47)), UNAM ([#48](https://github.com/openwatersio/stillwell/issues/48)), and BOM and DMI ([#80](https://github.com/openwatersio/stillwell/issues/80), which also records SANHO's refusal). GESLA's [license page](https://gesla787883612.wordpress.com/license/) says which contributors' data may be used for consultancy as well as research; a record's \`commercial_use\` is the stricter of that and the originator's own terms where they're known, and [contributors.ts](contributors.ts) holds each contributor's. UHSLC's records take each record's terms from UHSLC's documentation files ([UHSLC contributors](../uhslc/contributors.md)); its South African records, Walvis Bay's and Lüderitz's are SANHO's. "Originator ID" counts the records whose site code gives an ID in the originator's store source, whether or not that source lists it; \`stations.parquet\` links others by nearness and name.

| Contributor | Name | Records | Commercial use | Originator ID | Terms |
| --- | --- | --: | --- | --: | --- |
${rows.join("\n")}
`,
);
console.log(`${list.length} records, ${rows.length} contributors`);
