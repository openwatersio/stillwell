/**
 * Writes docs/gesla-contributors.md: GESLA 4.1's records by contributor, with
 * the terms `src/sources/gesla/contributors.ts` tags them with, from the
 * release's metadata CSV as the adapter lists it.
 *
 *   node scripts/gesla-contributors.ts
 */
import { writeFile } from "node:fs/promises";
import { stations } from "../src/sources/gesla/index.ts";
import { CONTRIBUTORS } from "../src/sources/gesla/contributors.ts";

const list = await stations();
const groups = Map.groupBy(list, (s) => s.contributor);
const rows = [...groups]
  .sort(([a, x], [b, y]) => y.length - x.length || a.localeCompare(b))
  .map(([abbrev, records]) => {
    const c = CONTRIBUTORS[abbrev.toUpperCase()]!;
    const commercial = records.filter((s) => s.commercial_use).length;
    const use =
      commercial === records.length ? "yes" : commercial === 0 ? "no" : `${commercial} of them`;
    const linked = records.filter((s) => s.same_as.length).length;
    return `| ${abbrev} | ${c.name} | ${records.length} | ${use} | ${linked} | ${c.terms} |`;
  });

await writeFile(
  new URL("../docs/gesla-contributors.md", import.meta.url),
  `# GESLA contributors

Generated by \`node scripts/gesla-contributors.ts\` from GESLA 4.1's metadata, ${list.length} records. Every record GESLA serves is in the public lake, credited to GESLA and its contributor. GESLA's [license page](https://gesla787883612.wordpress.com/license/) says which contributors' data may be used for consultancy as well as research; a record's \`commercial_use\` is the stricter of that and the originator's own terms where they're known, and [src/sources/gesla/contributors.ts](../src/sources/gesla/contributors.ts) holds each contributor's. UHSLC's records take each record's terms from UHSLC's documentation files ([uhslc-contributors.md](uhslc-contributors.md)), and its South African records are the South African Navy Hydrographic Office's, non-commercial while SANHO is asked for permission to republish them ([#82](https://github.com/openwatersio/water-levels/issues/82)). "Originator ID" counts the records whose site code gives an ID in the originator's lake source, whether or not that source lists it; \`stations.parquet\` links others by nearness and name.

| Contributor | Name | Records | Commercial use | Originator ID | Terms |
| --- | --- | --: | --- | --: | --- |
${rows.join("\n")}
`,
);
console.log(`${list.length} records, ${rows.length} contributors`);
